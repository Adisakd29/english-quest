-- ===== ตรวจค่า SRS ที่ผิดปกติ (ป้องกันไว้ก่อน) =====
-- หมายเหตุแก้ไข: เดิมเขียนว่าบั๊ก NaN มาจากค่า NUMERIC เป็นข้อความ ซึ่งไม่ถูกต้อง —
-- srs_ease เป็น REAL ที่ pg ส่งกลับเป็นตัวเลข บั๊กจริงคือช่วงทบทวนไม่มีเพดาน (แก้ใน utils/srs.js)
-- ปกติคำสั่งนี้ไม่เปลี่ยนแถวใดเลย คงไว้เพื่อกันกรณีมีค่า NaN ค้างจากสาเหตุอื่น
UPDATE word_progress SET srs_ease = 2.5 WHERE srs_ease = 'NaN'::real;
